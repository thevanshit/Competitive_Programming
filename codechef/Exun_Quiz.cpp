void solve() {
    int n, s;
    cin >> n >> s;
    int c = (s + 3) / 4;
    int w = 4 * c - s;

    if(c + w <= n){
        cout << c + w << '\n';
    }
    else{
        cout << -1 << '\n';
    }
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--) solve();
}